const NODE_TYPE_ALIASES: Record<string, GraphNodeType> = {
  user: "user",
  ad_account: "ad_account",
  account: "ad_account",
  campaign: "campaign",
  adset: "adset",
  ad_set: "adset",
  ad: "ad",
  creative: "creative",
  adcreative: "creative",
};

export function parseGraphNodeType(input: string): GraphNodeType {
  const normalizedInput = input.trim().toLowerCase();
  const nodeType = NODE_TYPE_ALIASES[normalizedInput];

  if (!nodeType) {
    throw new FbCliError("INVALID_NODE_TYPE", `Unsupported node type: ${input}`, {
      supportedNodeTypes: Object.keys(NODE_TYPE_ALIASES),
    });
  }

  return nodeType;
}

export function listGraphNodes(): GraphNodeDefinition[] {
  return Object.values(GRAPH_RESOURCES);
}

export function listGraphEdges(nodeType: GraphNodeType): GraphEdgeDefinition[] {
  return Object.values(GRAPH_RESOURCES[nodeType].edges);
}

export function inferGraphNodeTypeFromId(id: string): GraphNodeType {
  if (id.startsWith("act_")) {
    return "ad_account";
  }

  for (const [nodeType, definition] of Object.entries(GRAPH_RESOURCES)) {
    for (const prefix of definition.idPrefixes) {
      if (id.startsWith(prefix)) {
        return nodeType as GraphNodeType;
      }
    }
  }

  if (/^\d+$/.test(id)) {
    throw new FbCliError(
      "AMBIGUOUS_GRAPH_ID",
      "Numeric Graph IDs are ambiguous. Pass --node-type for this command.",
      { id },
    );
  }

  throw new FbCliError("INVALID_GRAPH_ID", `Cannot infer node type from ID: ${id}`, { id });
}

export function normalizeGraphId(id: string): string {
  const normalizedId = id.trim().replace(/^\//, "");

  if (!normalizedId || normalizedId.includes("/")) {
    throw new FbCliError("INVALID_GRAPH_ID", `Invalid Graph ID: ${id}`, {
      id,
    });
  }

  return normalizedId;
}
