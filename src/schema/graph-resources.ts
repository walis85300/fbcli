export type GraphNodeType = "user" | "ad_account" | "campaign" | "adset" | "ad" | "creative";

export type GraphEdgeDefinition = {
  name: string;
  description: string;
  read: boolean;
  write: boolean;
  mvpReadAllowed: boolean;
};

export type GraphNodeDefinition = {
  type: GraphNodeType;
  displayName: string;
  rootPathTemplate: string;
  idPrefixes: string[];
  edges: Record<string, GraphEdgeDefinition>;
};

const edge = (
  name: string,
  description: string,
  options: { read?: boolean; write?: boolean; mvpReadAllowed?: boolean } = {},
): GraphEdgeDefinition => ({
  name,
  description,
  read: options.read ?? true,
  write: options.write ?? false,
  mvpReadAllowed: options.mvpReadAllowed ?? true,
});

